function envoy_on_request(request_handle)
  run_test("sslConnection on request returns parsed tlsVersion", function()
    local streamInfo = request_handle:streamInfo()
    local ssl = streamInfo:downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    assert(ssl:tlsVersion() == "TLSv1.2", "Expected tls_version to be TLSv1.2")
  end)

  run_test("sslConnection on request parses peerCertificatePresented", function()
    local streamInfo = request_handle:streamInfo()
    local ssl = streamInfo:downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    assert(ssl:peerCertificatePresented() == true, "Expected peerCertificatePresented to return true")
  end)

  run_test("sslConnection on request handles missing peerCertificateValidated natively", function()
    local streamInfo = request_handle:streamInfo()
    local ssl = streamInfo:downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    assert(ssl:peerCertificateValidated() == false, "Expected peerCertificateValidated to return false based on missing property fallback")
  end)

  run_test("sslConnection on request returns subjectPeerCertificate string", function()
    local streamInfo = request_handle:streamInfo()
    local ssl = streamInfo:downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    local subject = ssl:subjectPeerCertificate()
    assert(subject == "CN=IntegrationTest", "Expected subject to be CN=IntegrationTest")
  end)

  run_test("sslConnection on request parses sha256PeerCertificateDigest", function()
    local ssl = request_handle:streamInfo():downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    assert(ssl:sha256PeerCertificateDigest() == "abcd1234digest")
  end)

  run_test("sslConnection on request parses subjectLocalCertificate", function()
    local ssl = request_handle:streamInfo():downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    assert(ssl:subjectLocalCertificate() == "CN=LocalTest")
  end)

  run_test("sslConnection on request parses validFromPeerCertificate", function()
    local ssl = request_handle:streamInfo():downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    assert(ssl:validFromPeerCertificate() == 8)
  end)

  run_test("sslConnection on request parses expirationPeerCertificate", function()
    local ssl = request_handle:streamInfo():downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    assert(ssl:expirationPeerCertificate() == 9)
  end)

  run_test("sslConnection on request parses uriSanPeerCertificate", function()
    local ssl = request_handle:streamInfo():downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    local uri_sans = ssl:uriSanPeerCertificate()
    assert(#uri_sans == 1)
    assert(uri_sans[1] == "spiffe://peer1")
  end)

  run_test("sslConnection on request parses uriSanLocalCertificate", function()
    local ssl = request_handle:streamInfo():downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    local local_sans = ssl:uriSanLocalCertificate()
    assert(#local_sans == 1)
    assert(local_sans[1] == "spiffe://local1")
  end)

  run_test("sslConnection on request parses dnsSansPeerCertificate", function()
    local ssl = request_handle:streamInfo():downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    local dns_sans = ssl:dnsSansPeerCertificate()
    assert(#dns_sans == 1)
    assert(dns_sans[1] == "peer1.com")
  end)

  run_test("sslConnection on request parses dnsSansLocalCertificate", function()
    local ssl = request_handle:streamInfo():downstreamSslConnection()
    assert(ssl ~= nil, "ssl should not be nil")
    local dns_sans_local = ssl:dnsSansLocalCertificate()
    assert(#dns_sans_local == 1)
    assert(dns_sans_local[1] == "local1.com")
  end)
end

