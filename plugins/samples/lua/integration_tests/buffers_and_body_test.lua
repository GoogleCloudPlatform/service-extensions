function envoy_on_request(request_handle)
  run_test("request buffer retrieves buffer length and contents correctly", function()
     local body = request_handle:body()
     assert(body, "body should not be nil")
     local len = body:length()
     assert(type(len) == "number", "length should be a number")
     local contents = body:getBytes(0, len)
     assert(type(contents) == "string", "body contents should be a string")
     assert(string.len(contents) == len, "body contents length should match len")
     print(string.format("read request body '%s'", contents))
  end)
end

